<#
lesson.ps1 - maintain a per-skill experience ledger.

A lesson is a REUSABLE rule ("when X happens, do Y"), not project state.
The ledger (knowledge\ledger.json) is the source of truth; knowledge\lessons.md
is generated from it so it stays compact and greppable.

USAGE
  lesson.ps1 list  -Skill windows-gui-control
  lesson.ps1 add   -Skill windows-gui-control -Key gui.handle.rebuild -Text "..." -Confidence 4 -Evidence "QQ x3"
  lesson.ps1 hit   -Skill windows-gui-control -Key gui.handle.rebuild
  lesson.ps1 miss  -Skill windows-gui-control -Key gui.handle.rebuild
  lesson.ps1 prune -Skill windows-gui-control [-Max 40]

RULES
  * hit  : hits++ ; every 3 hits raise confidence by 1 (max 5)
  * miss : misses++ ; when misses - hits >= 2 lower confidence by 1;
           at confidence 1 the entry becomes status=refuted (kept, never used)
  * prune: over -Max entries, drop the weakest (refuted first, then low
           confidence, then oldest last_verified, then fewest hits)
  * scope: "gui" | "embed" | "io" | "meta" - keep one domain per skill
This file stays pure ASCII: PowerShell 5.1 reads .ps1 as ANSI.
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory=$true)][ValidateSet('list','add','hit','miss','prune')][string]$Action,
  [Parameter(Mandatory=$true)][string]$Skill,
  [string]$Key,
  [string]$Text,
  [string]$Evidence,
  [string]$Scope = 'gui',
  [int]$Confidence = 3,
  [int]$Max = 40,
  [string]$SkillsRoot = (Join-Path $env:USERPROFILE '.agents\skills')
)

$ErrorActionPreference = 'Stop'
$kd = Join-Path $SkillsRoot (Join-Path $Skill 'knowledge')
if(-not (Test-Path $kd)){ New-Item -ItemType Directory -Path $kd -Force | Out-Null }
$ledgerPath  = Join-Path $kd 'ledger.json'
$lessonsPath = Join-Path $kd 'lessons.md'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Ledger {
  if(Test-Path $ledgerPath){
    $raw = [System.IO.File]::ReadAllText($ledgerPath, [System.Text.Encoding]::UTF8)
    if($raw.Trim()){ return ($raw | ConvertFrom-Json) }
  }
  return [pscustomobject]@{ skill = $Skill; updated = ''; entries = @() }
}

function Save-Ledger($ledger){
  $ledger.skill = $Skill
  $ledger.updated = (Get-Date).ToString('yyyy-MM-dd HH:mm')
  $json = $ledger | ConvertTo-Json -Depth 6
  [System.IO.File]::WriteAllText($ledgerPath, $json, $utf8)
  Write-Lessons $ledger
}

function Write-Lessons($ledger){
  $rows = @()
  $sorted = $ledger.entries | Sort-Object @{Expression={ if($_.status -eq 'refuted'){1}else{0} }}, @{Expression={[int]$_.confidence};Descending=$true}, @{Expression={$_.key}}
  foreach($e in $sorted){
    $flag = if($e.status -eq 'refuted'){ '[REFUTED] ' } else { '' }
    $rows += ('| {0} | {1} | {2}/{3} | {4}{5} |' -f $e.key, $e.confidence, $e.hits, $e.misses, $flag, $e.statement)
  }
  $head = @(
    ('# Experience ledger - ' + $Skill),
    '',
    '> Generated by scripts\lesson.ps1. Do not edit by hand.',
    '> Test for an entry: would this sentence still help on a DIFFERENT task? Project parameters, accounts and one-off coordinates do not belong here.',
    '',
    '| key | conf | hits/misses | lesson |',
    '|---|---|---|---|'
  )
  $out = ($head + $rows) -join "`r`n"
  [System.IO.File]::WriteAllText($lessonsPath, $out + "`r`n", $utf8)
}

function Find-Entry($ledger, $key){
  return ($ledger.entries | Where-Object { $_.key -eq $key } | Select-Object -First 1)
}

$ledger = Read-Ledger
$ledger.entries = @($ledger.entries)

switch($Action){

  'list' {
    Write-Lessons $ledger
    Write-Output ("skill : " + $Skill)
    Write-Output ("count : " + @($ledger.entries).Count)
    foreach($e in ($ledger.entries | Sort-Object @{Expression={[int]$_.confidence};Descending=$true})){
      Write-Output ("  [{0}] {1} {2}  hits={3} misses={4}  {5}" -f $e.confidence, $e.key, $e.status, $e.hits, $e.misses, $e.statement)
    }
  }

  'add' {
    if(-not $Key -or -not $Text){ throw 'add needs -Key and -Text' }
    $now = (Get-Date).ToString('yyyy-MM-dd')
    $e = Find-Entry $ledger $Key
    if($e){
      if($Text){ $e.statement = $Text }
      if($Evidence){ $e.evidence = $Evidence }
      if($Confidence -gt [int]$e.confidence){ $e.confidence = $Confidence }
      $e.last_verified = $now
      Write-Output ("updated " + $Key)
    } else {
      $entry = [pscustomobject]@{
        key = $Key; statement = $Text; scope = $Scope
        confidence = $Confidence; hits = 0; misses = 0
        status = 'active'; evidence = $Evidence
        added = $now; last_verified = $now
      }
      $ledger.entries += $entry
      Write-Output ("added " + $Key)
    }
    Save-Ledger $ledger
  }

  'hit' {
    $e = Find-Entry $ledger $Key
    if(-not $e){ throw ("no such key: " + $Key) }
    $e.hits = [int]$e.hits + 1
    $e.last_verified = (Get-Date).ToString('yyyy-MM-dd')
    if(($e.hits % 3) -eq 0 -and [int]$e.confidence -lt 5){ $e.confidence = [int]$e.confidence + 1 }
    Write-Output ("hit  " + $Key + "  hits=" + $e.hits + " conf=" + $e.confidence)
    Save-Ledger $ledger
  }

  'miss' {
    $e = Find-Entry $ledger $Key
    if(-not $e){ throw ("no such key: " + $Key) }
    $e.misses = [int]$e.misses + 1
    if(([int]$e.misses - [int]$e.hits) -ge 2){
      $e.confidence = [math]::Max(1, [int]$e.confidence - 1)
      if([int]$e.confidence -le 1){ $e.status = 'refuted' }
    }
    Write-Output ("miss " + $Key + "  misses=" + $e.misses + " conf=" + $e.confidence + " status=" + $e.status)
    Save-Ledger $ledger
  }

  'prune' {
    $all = @($ledger.entries)
    if($all.Count -le $Max){ Write-Output ("nothing to prune (" + $all.Count + " <= " + $Max + ")"); return }
    $keep = $all | Sort-Object @{Expression={ if($_.status -eq 'refuted'){1}else{0} }}, @{Expression={[int]$_.confidence};Descending=$true}, @{Expression={$_.last_verified};Descending=$true}, @{Expression={[int]$_.hits};Descending=$true} | Select-Object -First $Max
    $drop = $all | Where-Object { $keep.key -notcontains $_.key }
    $ledger.entries = @($keep)
    Write-Output ("dropped: " + (($drop | ForEach-Object { $_.key }) -join ', '))
    Save-Ledger $ledger
  }
}
